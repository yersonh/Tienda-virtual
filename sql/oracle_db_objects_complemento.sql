CREATE OR REPLACE FUNCTION FN_PEDIDO_PUEDE_CANCELARSE(p_id_pedido IN NUMBER)
RETURN NUMBER
AS
    v_total NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_total
    FROM PEDIDO
    WHERE ID_PEDIDO = p_id_pedido
      AND ID_ESTADO IN (1, 2);

    RETURN CASE WHEN v_total > 0 THEN 1 ELSE 0 END;
END;
/

CREATE OR REPLACE FUNCTION FN_DIRECCION_PREDETERMINADA(p_id_usuario IN NUMBER)
RETURN NUMBER
AS
    v_id DIRECCION_USUARIO.ID_DIRECCION%TYPE;
BEGIN
    SELECT ID_DIRECCION
    INTO v_id
    FROM DIRECCION_USUARIO
    WHERE ID_USUARIO = p_id_usuario
      AND ES_PREDETERMINADA = 1
    FETCH FIRST 1 ROWS ONLY;

    RETURN v_id;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN NULL;
END;
/

