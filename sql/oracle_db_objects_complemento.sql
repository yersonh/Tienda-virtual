CREATE OR REPLACE PROCEDURE SP_AGREGAR_CARRITO (
    p_id_usuario IN NUMBER,
    p_id_producto IN NUMBER,
    p_id_referencia IN NUMBER,
    p_cantidad IN NUMBER
)
AS
    v_id_carrito NUMBER;
    v_id_detalle NUMBER;
BEGIN
    BEGIN
        SELECT ID_CARRITO INTO v_id_carrito
        FROM CARRITO
        WHERE ID_USUARIO = p_id_usuario
        FOR UPDATE;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            INSERT INTO CARRITO (ID_USUARIO)
            VALUES (p_id_usuario)
            RETURNING ID_CARRITO INTO v_id_carrito;
    END;

    BEGIN
        SELECT ID_DETALLE INTO v_id_detalle
        FROM DETALLE_CARRITO
        WHERE ID_CARRITO = v_id_carrito
          AND ID_PRODUCTO = p_id_producto
          AND ID_REFERENCIA = p_id_referencia
        FOR UPDATE;

        UPDATE DETALLE_CARRITO
        SET CANTIDAD = CANTIDAD + p_cantidad,
            SELECCIONADO = 1
        WHERE ID_DETALLE = v_id_detalle;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            INSERT INTO DETALLE_CARRITO (
                ID_CARRITO,
                ID_PRODUCTO,
                ID_REFERENCIA,
                CANTIDAD,
                SELECCIONADO
            ) VALUES (
                v_id_carrito,
                p_id_producto,
                p_id_referencia,
                p_cantidad,
                1
            );
    END;
END;
/

CREATE OR REPLACE PROCEDURE SP_ACTUALIZAR_CARRITO (
    p_id_usuario IN NUMBER,
    p_id_producto IN NUMBER,
    p_id_referencia IN NUMBER,
    p_cantidad IN NUMBER
)
AS
    v_id_carrito NUMBER;
BEGIN
    SELECT ID_CARRITO INTO v_id_carrito
    FROM CARRITO
    WHERE ID_USUARIO = p_id_usuario;

    UPDATE DETALLE_CARRITO
    SET CANTIDAD = p_cantidad
    WHERE ID_CARRITO = v_id_carrito
      AND ID_PRODUCTO = p_id_producto
      AND ID_REFERENCIA = p_id_referencia;
END;
/

