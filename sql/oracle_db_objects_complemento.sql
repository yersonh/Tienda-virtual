DECLARE
    PROCEDURE crear_seq(p_nombre VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
        FROM USER_SEQUENCES
        WHERE SEQUENCE_NAME = UPPER(p_nombre);

        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'CREATE SEQUENCE ' || p_nombre || ' START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE';
        END IF;
    END;
BEGIN
    crear_seq('SEQ_PERSONA');
    crear_seq('SEQ_USUARIO');
    crear_seq('SEQ_CLIENTE');
    crear_seq('SEQ_PRODUCTO');
    crear_seq('SEQ_PRODUCTO_IMAGEN');
    crear_seq('SEQ_CARRITO');
    crear_seq('SEQ_DETALLE_CARRITO');
    crear_seq('SEQ_DIRECCION_USUARIO');
    crear_seq('SEQ_DIRECCION_PEDIDO');
    crear_seq('SEQ_VENTA');
    crear_seq('SEQ_DETALLE_VENTA');
    crear_seq('SEQ_PEDIDO');
    crear_seq('SEQ_PAGO');
    crear_seq('SEQ_PASSWORD_RESETS');
    crear_seq('SEQ_METODO_PAGO_USUARIO');
END;
/

