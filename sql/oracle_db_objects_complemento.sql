CREATE OR REPLACE TRIGGER TRG_PERSONA_BI
BEFORE INSERT ON PERSONA
FOR EACH ROW
BEGIN
    IF :NEW.ID_PERSONA IS NULL THEN
        SELECT SEQ_PERSONA.NEXTVAL INTO :NEW.ID_PERSONA FROM DUAL;
    END IF;

    :NEW.CORREO := LOWER(TRIM(:NEW.CORREO));
    :NEW.TELEFONO := REGEXP_REPLACE(:NEW.TELEFONO, '[^0-9]', '');
