    v_id_carrito NUMBER;
BEGIN
    SELECT ID_CARRITO INTO v_id_carrito
    FROM CARRITO
    WHERE ID_USUARIO = p_id_usuario;

    DELETE FROM DETALLE_CARRITO
    WHERE ID_CARRITO = v_id_carrito
      AND ID_PRODUCTO = p_id_producto
      AND ID_REFERENCIA = p_id_referencia;
END;
/

CREATE OR REPLACE PROCEDURE SP_VACIAR_CARRITO (
    p_id_usuario IN NUMBER
)
AS
    v_id_carrito NUMBER;
BEGIN
    SELECT ID_CARRITO INTO v_id_carrito
    FROM CARRITO
    WHERE ID_USUARIO = p_id_usuario;

    DELETE FROM DETALLE_CARRITO
    WHERE ID_CARRITO = v_id_carrito;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        NULL;
END;
/

CREATE OR REPLACE PROCEDURE SP_CANCELAR_PEDIDO (
    p_id_pedido IN NUMBER,
    p_id_usuario IN NUMBER
)
AS
    v_id_estado PEDIDO.ID_ESTADO%TYPE;
BEGIN
    SELECT p.ID_ESTADO
    INTO v_id_estado
    FROM PEDIDO p
    JOIN VENTA v ON v.ID_VENTA = p.ID_VENTA
    WHERE p.ID_PEDIDO = p_id_pedido
      AND v.ID_USUARIO = p_id_usuario
    FOR UPDATE;

    IF v_id_estado IN (3, 4) THEN
        RAISE_APPLICATION_ERROR(-20121, 'El pedido ya esta en camino o fue entregado');
    ELSIF v_id_estado = 5 THEN
        RAISE_APPLICATION_ERROR(-20122, 'Pedido cancelado');
    ELSIF v_id_estado NOT IN (1, 2) THEN
        RAISE_APPLICATION_ERROR(-20120, 'No se puede cancelar el pedido');
    END IF;

    UPDATE PEDIDO
    SET ID_ESTADO = 5
    WHERE ID_PEDIDO = p_id_pedido;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20120, 'No se puede cancelar el pedido');
END;
/

CREATE OR REPLACE PROCEDURE SP_EXPIRAR_PEDIDOS
AS
BEGIN
    UPDATE PEDIDO p
    SET p.ID_ESTADO = 5
    WHERE p.ID_ESTADO = 1
      AND p.CREATED_AT IS NOT NULL
      AND CAST(p.CREATED_AT AS TIMESTAMP) < SYSTIMESTAMP - INTERVAL '5' MINUTE
      AND NOT EXISTS (
          SELECT 1
          FROM PAGO pg
          WHERE pg.ID_VENTA = p.ID_VENTA
            AND UPPER(TRIM(pg.ESTADO)) IN ('APPROVED', 'PAGADO', 'COMPLETADO')
      );
END;
