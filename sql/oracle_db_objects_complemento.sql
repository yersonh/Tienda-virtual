CREATE OR REPLACE FUNCTION FN_TOTAL_CARRITO(
    p_id_usuario IN NUMBER,
    p_solo_seleccionados IN NUMBER DEFAULT 0
) RETURN NUMBER
AS
    v_total NUMBER(10,2);
BEGIN
    SELECT NVL(SUM(p.PRECIO * dc.CANTIDAD), 0)
    INTO v_total
    FROM CARRITO c
    JOIN DETALLE_CARRITO dc ON dc.ID_CARRITO = c.ID_CARRITO
    JOIN PRODUCTO p ON p.ID_PRODUCTO = dc.ID_PRODUCTO
    WHERE c.ID_USUARIO = p_id_usuario
      AND (p_solo_seleccionados = 0 OR NVL(dc.SELECCIONADO, 0) = 1);

    RETURN v_total;
END;
/

CREATE OR REPLACE FUNCTION FN_TOTAL_VENTA(
    p_id_venta IN NUMBER
) RETURN NUMBER
AS
    v_total NUMBER(10,2);
BEGIN
    SELECT NVL(SUM(SUBTOTAL), 0)
    INTO v_total
    FROM DETALLE_VENTA
    WHERE ID_VENTA = p_id_venta;

    RETURN v_total;
END;
/

CREATE OR REPLACE FUNCTION FN_USUARIO_EXISTE(p_username IN VARCHAR2)
RETURN NUMBER
AS
    v_total NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_total
    FROM USUARIO
    WHERE LOWER(USERNAME) = LOWER(TRIM(p_username));

    RETURN CASE WHEN v_total > 0 THEN 1 ELSE 0 END;
END;
/

