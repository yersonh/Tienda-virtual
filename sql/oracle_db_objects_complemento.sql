CREATE OR REPLACE VIEW V_DETALLE_PEDIDO AS
SELECT
    pe.ID_PEDIDO,
    pe.ID_ESTADO,
    ep.NOMBRE AS ESTADO,
    v.ID_VENTA,
    v.ID_USUARIO,
    v.FECHA,
    v.SUBTOTAL,
    v.IVA,
    v.ENVIO,
    v.TOTAL,
    dv.ID_PRODUCTO,
    dv.CANTIDAD,
    dv.PRECIO_UNITARIO,
    dv.SUBTOTAL AS SUBTOTAL_PRODUCTO,
    dv.NOMBRE_PRODUCTO
FROM PEDIDO pe
JOIN VENTA v ON v.ID_VENTA = pe.ID_VENTA
JOIN ESTADO_PEDIDO ep ON ep.ID_ESTADO = pe.ID_ESTADO
LEFT JOIN DETALLE_VENTA dv ON dv.ID_VENTA = v.ID_VENTA;
/

CREATE OR REPLACE VIEW V_ADMIN_PEDIDOS AS
SELECT
    p.ID_PEDIDO,
    p.ID_VENTA,
    p.ID_ESTADO,
    e.NOMBRE AS ESTADO,
