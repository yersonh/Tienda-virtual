CREATE OR REPLACE VIEW V_USUARIO_COMPLETO AS
SELECT
    u.ID_USUARIO,
    u.ID_PERSONA,
    u.ID_TIPO,
    u.USERNAME,
    u.ESTADO,
    p.NOMBRES,
    p.APELLIDOS,
    p.CORREO,
    p.TELEFONO,
    p.DIRECCION,
    tu.NOMBRE AS TIPO_USUARIO
FROM USUARIO u
JOIN PERSONA p ON p.ID_PERSONA = u.ID_PERSONA
JOIN TIPO_USUARIO tu ON tu.ID_TIPO = u.ID_TIPO;
/

CREATE OR REPLACE VIEW V_PRODUCTOS_ADMIN AS
SELECT
    p.ID_PRODUCTO,
    p.NOMBRE,
    p.CODIGO,
    p.DESCRIPCION,
    p.PRECIO,
    p.ESTADO,
    p.ID_CATEGORIA,
    c.NOMBRE AS CATEGORIA_NOMBRE,
    img.IMAGEN
FROM PRODUCTO p
JOIN CATEGORIA_PRODUCTO c ON c.ID_CATEGORIA = p.ID_CATEGORIA
LEFT JOIN (
    SELECT ID_PRODUCTO,
           MIN(URL) KEEP (DENSE_RANK FIRST ORDER BY NVL(ORDEN, 999999), ID_IMAGEN) AS IMAGEN
    FROM PRODUCTO_IMAGEN
    GROUP BY ID_PRODUCTO
) img ON img.ID_PRODUCTO = p.ID_PRODUCTO;
/

CREATE OR REPLACE VIEW V_CARRITO_USUARIO AS
SELECT
    c.ID_USUARIO,
    c.ID_CARRITO,
    dc.ID_DETALLE,
    dc.ID_PRODUCTO,
    dc.ID_REFERENCIA,
    dc.CANTIDAD,
    NVL(dc.SELECCIONADO, 0) AS SELECCIONADO,
    p.NOMBRE,
    p.PRECIO,
    p.PRECIO * dc.CANTIDAD AS SUBTOTAL
FROM CARRITO c
JOIN DETALLE_CARRITO dc ON dc.ID_CARRITO = c.ID_CARRITO
JOIN PRODUCTO p ON p.ID_PRODUCTO = dc.ID_PRODUCTO;
/

CREATE OR REPLACE VIEW V_DIRECCIONES_USUARIO AS
SELECT
    ID_DIRECCION,
    ID_USUARIO,
    NOMBRE,
    APELLIDO,
    DIRECCION,
    CIUDAD,
    BARRIO,
    TELEFONO,
    TELEFONO_ALT,
