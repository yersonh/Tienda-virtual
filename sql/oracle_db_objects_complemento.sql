CREATE OR REPLACE TRIGGER TRG_DIRECCION_UNICA_PREDET
FOR INSERT OR UPDATE OF ES_PREDETERMINADA ON DIRECCION_USUARIO
COMPOUND TRIGGER
    TYPE t_ids IS TABLE OF DIRECCION_USUARIO.ID_DIRECCION%TYPE INDEX BY PLS_INTEGER;
    TYPE t_users IS TABLE OF DIRECCION_USUARIO.ID_USUARIO%TYPE INDEX BY PLS_INTEGER;
    g_ids t_ids;
    g_users t_users;
    g_count PLS_INTEGER := 0;

    AFTER EACH ROW IS
    BEGIN
        IF :NEW.ES_PREDETERMINADA = 1 THEN
            g_count := g_count + 1;
            g_ids(g_count) := :NEW.ID_DIRECCION;
            g_users(g_count) := :NEW.ID_USUARIO;
        END IF;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
    BEGIN
        FOR i IN 1 .. g_count LOOP
            UPDATE DIRECCION_USUARIO
            SET ES_PREDETERMINADA = 0
            WHERE ID_USUARIO = g_users(i)
              AND ID_DIRECCION <> g_ids(i)
              AND ES_PREDETERMINADA = 1;
        END LOOP;
    END AFTER STATEMENT;
END;
/

