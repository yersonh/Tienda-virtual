CREATE OR REPLACE TRIGGER TRG_DETALLE_VENTA_BI
BEFORE INSERT ON DETALLE_VENTA
FOR EACH ROW
DECLARE
    v_precio PRODUCTO.PRECIO%TYPE;
    v_nombre PRODUCTO.NOMBRE%TYPE;
BEGIN
    IF :NEW.ID_DETALLE IS NULL THEN
        SELECT SEQ_DETALLE_VENTA.NEXTVAL INTO :NEW.ID_DETALLE FROM DUAL;
    END IF;

    SELECT PRECIO, NOMBRE
    INTO v_precio, v_nombre
    FROM PRODUCTO
    WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;

    :NEW.PRECIO_UNITARIO := NVL(:NEW.PRECIO_UNITARIO, v_precio);
    :NEW.NOMBRE_PRODUCTO := NVL(:NEW.NOMBRE_PRODUCTO, SUBSTR(v_nombre, 1, 150));
    :NEW.SUBTOTAL := NVL(:NEW.SUBTOTAL, :NEW.CANTIDAD * :NEW.PRECIO_UNITARIO);
END;
