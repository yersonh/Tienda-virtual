-- Trigger para asignar ID_REFERENCIA automaticamente
CREATE OR REPLACE TRIGGER TRG_REFERENCIA_PRODUCTO_BI
BEFORE INSERT ON REFERENCIA_PRODUCTO
FOR EACH ROW
BEGIN
  IF :NEW.ID_REFERENCIA IS NULL THEN
    SELECT SEQ_REFERENCIA_PRODUCTO.NEXTVAL INTO :NEW.ID_REFERENCIA FROM DUAL;
  END IF;
  :NEW.ESTADO := NVL(:NEW.ESTADO, 'Activo');
END;
/

