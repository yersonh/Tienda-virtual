-- Secuencias e triggers para REFERENCIA_PRODUCTO y tablas de compatibilidad
-- Ejecutar en SQL Developer / SQLcl (idempotente)

-- Secuencia para REFERENCIA_PRODUCTO
BEGIN
  EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_REFERENCIA_PRODUCTO START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

